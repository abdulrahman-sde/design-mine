function usePausableTimers(paused: boolean) {
  const pausedRef = useRef(paused);
  const timersRef = useRef<
    Set<{
      id: ReturnType<typeof setTimeout> | null;
      remainingMs: number;
      run: () => void;
      startedAt: number;
    }>
  >(new Set());

  const startEntry = useCallback(
    (entry: {
      id: ReturnType<typeof setTimeout> | null;
      remainingMs: number;
      run: () => void;
      startedAt: number;
    }) => {
      entry.startedAt = performance.now();
      entry.id = setTimeout(() => {
        entry.id = null;
        timersRef.current.delete(entry);
        entry.run();
      }, entry.remainingMs);
    },
    []
  );

  const schedule = useCallback(
    (run: () => void, ms: number) => {
      const entry = {
        id: null as ReturnType<typeof setTimeout> | null,
        remainingMs: ms,
        run,
        startedAt: 0,
      };
      timersRef.current.add(entry);
      if (!pausedRef.current) startEntry(entry);
      return () => {
        if (entry.id) clearTimeout(entry.id);
        timersRef.current.delete(entry);
      };
    },
    [startEntry]
  );

  useEffect(() => {
    pausedRef.current = paused;
    if (paused) {
      const now = performance.now();
      timersRef.current.forEach((entry) => {
        if (entry.id) {
          clearTimeout(entry.id);
          entry.id = null;
          entry.remainingMs = Math.max(
            0,
            entry.remainingMs - (now - entry.startedAt)
          );
        }
      });
      return;
    }
    timersRef.current.forEach((entry) => {
      if (!entry.id) startEntry(entry);
    });
  }, [paused, startEntry]);

  useEffect(
    () => () => {
      timersRef.current.forEach((entry) => {
        if (entry.id) clearTimeout(entry.id);
      });
      timersRef.current.clear();
    },
    []
  );

  return schedule;
}

type Point = { x: number; y: number };
type PointerLayerData = {
  frame: HTMLElement;
  path: { start: Point; control: Point; end: Point };
  keyframes: Point[];
};

const sampleBezier = (start: Point, control: Point, end: Point): Point[] =>
  Array.from({ length: 29 }, (_, idx) => {
    const t = 1 - (1 - idx / 28) ** 3;
    const u = 1 - t;
    return {
      x: u * u * start.x + 2 * u * t * control.x + t * t * end.x,
      y: u * u * start.y + 2 * u * t * control.y + t * t * end.y,
    };
  });

const getFrameMetrics = (frame: HTMLElement) => {
  const rect = frame.getBoundingClientRect();
  if (
    frame.offsetWidth === 0 ||
    frame.offsetHeight === 0 ||
    rect.width === 0 ||
    rect.height === 0
  )
    return null;
  const scaleX = rect.width / frame.offsetWidth;
  const scaleY = rect.height / frame.offsetHeight;
  return scaleX === 0 || scaleY === 0
    ? null
    : { frameRect: rect, frameScaleX: scaleX, frameScaleY: scaleY };
};

const computePointerPath = (frame: HTMLElement, target: Point) => {
  const m = getFrameMetrics(frame);
  if (!m) return null;
  const { frameRect, frameScaleY } = m;
  const minX = 0.04 * frame.offsetWidth;
  const parentRect = frame.parentElement?.getBoundingClientRect();
  const visibleH = parentRect
    ? (Math.min(frameRect.bottom, parentRect.bottom) - frameRect.top) /
      frameScaleY
    : frame.offsetHeight;
  const start = {
    x: target.x - (target.x - minX) * (1 / 3),
    y: Math.min(640, visibleH - 28),
  };
  const corner = { x: start.x, y: target.y };
  const mid = { x: (start.x + target.x) / 2, y: (start.y + target.y) / 2 };
  const control = {
    x: corner.x + (mid.x - corner.x) * 0.45,
    y: corner.y + (mid.y - corner.y) * 0.45,
  };
  return { start, control, end: target };
};

